    # Set the body of an HTTP request
    #
    # @param [Net::HTTPGenericRequest] request the request
    # @param [Hash] form_params Form parameters
    # @param [Object] body HTTP body (JSON/XML)
    def build_request_body(request, form_params, body)
      # http form
      if request['Content-Type'] == 'application/x-www-form-urlencoded'
        request.set_form_data(form_params)
        return
      end
      return if body.nil?

      data = body.is_a?(String) ? body : body.to_json
      if request['Content-Encoding'] == 'gzip'
        gzip = Zlib::Deflate.new(nil, Zlib::MAX_WBITS + 16)
        data = gzip.deflate(data, Zlib::FINISH)
        gzip.close
      elsif request['Content-Encoding'] == 'deflate'
        data = Zlib::deflate(data)
      elsif request['Content-Encoding'] == 'zstd1'
        data = Zstandard.deflate(data)
      end
      request.body = data
    end

    # Wrap the files of multipart form parameters, so that they are sent as file parts.
    #
    # @param [Hash] form_params Form parameters
    # @return [Hash] the parameters of a multipart request
    def build_multipart_params(form_params)
      form_params.each_with_object({}) do |(key, value), params|
        params[key] = if value.respond_to?(:content_type) && value.respond_to?(:original_filename)
          value
        elsif value.respond_to?(:path) && value.respond_to?(:read)
          mime = MiniMime.lookup_by_filename(value.path)
          content_type = mime ? mime.content_type : 'application/octet-stream'
          Multipart::Post::UploadIO.new(value, content_type)
        else
          value
        end
      end
    end

